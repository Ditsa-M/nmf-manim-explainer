"""Build NMF_explained.srt and SCRIPT.md from the captions the scenes logged.

Usage: python3 make_script.py <resolution dir, e.g. 1080p60> <srt output path>

Scene offsets come from the rendered scene videos (ffprobe), so the
timestamps match the concatenated video exactly.
"""
import ast
import json
import subprocess
import sys

RES, SRT = sys.argv[1], sys.argv[2]

SCENES = next(ast.literal_eval(n.value) for n in ast.parse(open("nmf.py").read()).body
              if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "SCENES")
TITLES = {
    "S01Intro": "Intro and the four questions", "S02Input": "What goes in", "S03Output": "What comes out",
    "S04Fitting": "How W and H are found", "S05KeptLost": "Geometric view: kept vs lost",
    "S06Kinetics": "Use case: catching a reaction intermediate", "S07Knobs": "The researcher's choices",
    "S08Questions": "Biochemical questions NMF makes easier", "S09Paper": "The paper and its data",
    "S10Method": "How the paper used NMF", "S11KeyFigure": "Key figure and biological insight",
    "S12StrengthsLimits": "Strengths, failure modes and artifacts",
    "S13Theory": "Graduate level: uniqueness and complexity",
    "S14Conclusions": "Unjustified conclusions; the four questions; further reading",
}
PARTS = [("1 · How the transform works", "S01Intro"), ("2 · Biochemical use case", "S06Kinetics"),
         ("3 · Primary literature", "S09Paper"), ("4 · Strengths & limitations", "S12StrengthsLimits")]


def dur(scene):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                          f"media/videos/nmf/{RES}/{scene}.mp4"], capture_output=True, text=True, check=True)
    return float(out.stdout)


def mmss(t):
    return f"{int(t // 60)}:{int(t % 60):02d}"


def srt_time(t):
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


offset, start, entries = 0.0, {}, []
for s in SCENES:
    start[s] = offset
    for c in json.load(open(f"media/captions/{s}.json"))["captions"]:
        entries.append((s, offset + c["start"], offset + c["end"], c["who"], c["text"]))
    offset += dur(s)
total = offset

with open(SRT, "w") as f:
    for i, (_, a, b, who, text) in enumerate(entries, 1):
        f.write(f"{i}\n{srt_time(a)} --> {srt_time(b)}\n{text}\n\n")

talk = {"A": 0.0, "B": 0.0}
words = {"A": 0, "B": 0}
for _, a, b, who, text in entries:
    talk[who] += b - a
    words[who] += len(text.split())

L = [
    "# NMF explained — two-speaker narration script",
    "",
    "*Generated by `make_script.py` from the captions in `nmf.py`. Edit the narration there, not here.*",
    "",
    f"The video runs **{mmss(total)}** against the 15-minute limit. The narration is burned into the video "
    "as captions; a separate soft-subtitle file, `NMF_explained.srt`, is attached to the release. Each "
    "caption stays on screen for as long as it takes to read aloud at 150 words per minute, so you can "
    "speak along with the captions.",
    "",
    f"- **Speaker A**: {words['A']} words, about {mmss(talk['A'])} of speaking",
    f"- **Speaker B**: {words['B']} words, about {mmss(talk['B'])} of speaking",
    "",
    "| Part | Starts |",
    "|---|---|",
]
L += [f"| {name} | {mmss(start[s])} |" for name, s in PARTS]
L.append("")

cur_part = None
for s in SCENES:
    for name, first in PARTS:
        if first == s:
            L += ["---", "", f"# Part {name}", ""]
    L.append(f"## {mmss(start[s])} · {TITLES.get(s, s)}")
    L.append("")
    who_prev = None
    for sc, a, b, who, text in entries:
        if sc != s:
            continue
        if who != who_prev:
            L.append(f"**Speaker {who}** *({mmss(a)})*")
            L.append("")
            who_prev = who
        L.append(text)
        L.append("")

t = {s: mmss(start[s]) for s in SCENES}
L += [
    "---", "",
    "## Rubric checklist", "",
    "| Criterion | Where it's covered |",
    "|---|---|",
    f"| Transform fundamentals (20) | {t['S02Input']} input (V ∈ ℝ≥0^(n×m), Beer–Lambert A = ℓCE); "
    f"{t['S03Output']} output (W, H, rank-k sum of outer products, compression); {t['S04Fitting']} objective, "
    f"Gaussian/Poisson likelihoods, gradient → multiplicative updates, KKT; {t['S05KeptLost']} geometry (cone vs "
    "PCA), kept vs lost, Eckart–Young |",
    f"| Biochemical relevance (20) | {t['S06Kinetics']} stopped-flow before/after (the required before/after "
    f"visual): intermediate spectrum and rate constants; {t['S07Knobs']} researcher's choices (PCA's few knobs vs "
    f"NMF's many); {t['S08Questions']} the range of biochemical questions |",
    f"| Literature (20) | {t['S09Paper']} what was measured and how it became V; {t['S10Method']} M ≈ PE, "
    f"bootstrap, choosing k, reproduced in miniature; {t['S11KeyFigure']} Fig. 2 signatures with causes, Fig. 3, "
    "biological insight |",
    f"| Critical evaluation (10) | {t['S12StrengthsLimits']} strengths; failure modes with computed evidence "
    f"(non-uniqueness, k too large, start dependence, baseline); {t['S13Theory']} identifiability "
    f"(WH = (WT)(T⁻¹H), simplex geometry), NP-hardness, separability; {t['S14Conclusions']} four conclusions "
    "that are **not** justified; reading list beginner → graduate |",
    f"| Teamwork & timing (10) | A {mmss(talk['A'])} vs B {mmss(talk['B'])} of speaking; total {mmss(total)} "
    "against the 15:00 limit; Q&A prep below |",
    "",
]
L.append(open("script_qa.md").read().rstrip())
open("SCRIPT.md", "w").write("\n".join(L) + "\n")
print(f"captions: {len(entries)}  total {mmss(total)}  A {words['A']} words / {mmss(talk['A'])}  "
      f"B {words['B']} words / {mmss(talk['B'])}")
